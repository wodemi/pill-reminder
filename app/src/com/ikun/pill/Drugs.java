    public static String label(int i) {
        return DATA[i][0] + "\u3000·\u3000" + DATA[i][1];
    }

    public static int indexOfName(String name) {
        for (int i = 0; i < DATA.length; i++) {
            if (DATA[i][0].equals(name)) return i;
        }
        return -1;
    }

    public static ArrayList<Integer> search(String q, String cat) {
        ArrayList<Integer> out = new ArrayList<>();
        String key = q == null ? "" : q.trim().toLowerCase();
        for (int i = 0; i < DATA.length; i++) {
            if (cat != null && !cat.isEmpty() && !DATA[i][2].equals(cat)) continue;
            if (key.isEmpty()
                    || DATA[i][0].toLowerCase().contains(key)
                    || DATA[i][2].toLowerCase().contains(key)) {
                out.add(i);
            }
        }
        return out;
    }

